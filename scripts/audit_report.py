"""Regenerate docs/AUDIT.md from the output files of the evaluator-v1 audit. No number in the
report is typed by hand: every figure is read from runs/audit_v1/ or docs/v1_test_output.txt.

Inputs (produced by the commands listed in the report's last section):
  runs/audit_v1/rewards_{raw,capped5,duration_pct}.{json,md}, acceptance.json   scripts/audit_rewards.py
  runs/audit_v1/diversity_level.json                                            scripts/audit_diversity_level.py
  runs/audit_v1/duration_correlation.json                                       scripts/audit_duration_correlation.py
  runs/audit_v1/survival.json                                                   scripts/audit_survival.py
  runs/audit_v1/bucket_choice.json                                              scripts/audit_bucket_choice.py
  runs/audit_v1/data_checks.json                                                scripts/audit_data_checks.py
  runs/differential_summary.json                                                scripts/differential.py
  docs/v1_test_output.txt                                                       pytest

Usage: .venv/bin/python scripts/audit_report.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from kuairec_eval import _integrity  # noqa: E402

A = ROOT / "runs" / "audit_v1"
REWARDS = ("raw", "capped5", "duration_pct")
LADDER = [("random", "random"), ("rotation_random", "rotation-random"),
          ("rotation_shortest", "duration probe: rotation, shortest pick"),
          ("rotation_longest", "duration probe: rotation, longest pick"),
          ("shortest_first", "duration probe: shortest first (plain)"),
          ("longest_first", "duration probe: longest first (plain)"),
          ("oracle_affinity_full_cycle", "category-affinity oracle, full cycle (baseline reading, C1)"),
          ("oracle_affinity_strict", "category-affinity oracle, strict rotation (window reading)"),
          ("oracle_affinity_free", "category-affinity oracle, free within the quit rule"),
          ("oracle_nonpersonalized", "non-personalized oracle"), ("oracle_personalized", "personalized oracle")]


def load(name):
    return json.loads((A / name).read_text())


def f(x, d=3):
    return f"{x:.{d}f}"


def ci(c, d=3):
    return f"[{f(c[0], d)}, {f(c[1], d)}]"


def table_without_header(md_path: Path) -> str:
    keep = [l for l in md_path.read_text().splitlines() if not l.startswith("### ") and not l.startswith("Command:")]
    return "\n".join(keep).strip()


def main():
    rewards = {r: load(f"rewards_{r}.json") for r in REWARDS}
    div = load("diversity_level.json")
    corr = load("duration_correlation.json")
    surv = load("survival.json")
    bucket = load("bucket_choice.json")
    checks = load("data_checks.json")
    diff = json.loads((ROOT / "runs" / "differential_summary.json").read_text())
    tests = (ROOT / "docs" / "v1_test_output.txt").read_text().strip().splitlines()[-1].strip("= ")
    digest = rewards["duration_pct"]["manifest_digest"]
    dp = rewards["duration_pct"]
    pol = dp["policies"]
    gap = dp["acceptance"]["T2_personalized_beats_nonpersonalized"]
    p_val = pol["oracle_personalized"]["summary"]["cum_reward"]["mean"]
    dec = div["decision"]
    d1_key = next(p for p, r in div["profiles"].items() if "d1_tolerance_mismatch" in r)
    L = []
    w = L.append

    w("# Evaluator v1 audit report\n")
    w("_Generated by `.venv/bin/python scripts/audit_report.py` from `runs/audit_v1/`, "
      "`runs/differential_summary.json` and `docs/v1_test_output.txt`. Do not edit by hand._\n")
    w(f"Evaluator v1 is frozen with manifest digest `{digest[:16]}...` and tagged `evaluator-v1`. The v0 audit that "
      "led here is commit `c8a9a0d` (`runs/audit/`, `docs/proposals/evaluator-v1.patch`). The holdout has not been read. "
      "All results use the search partition: 847 users, stochastic policies on seeds 0-9, deterministic ones on seed 0 "
      "with a determinism check on seed 1. Comparisons are paired bootstraps over users (10,000 resamples).\n")

    w("## 1. Final ladder under v1 (primary profile N=9, n_Q=1; reward duration_pct)\n")
    w("| Rung | Cum reward / session {95% users} [95% seeds] | Mean reward / rec | Session length | Share of personalized oracle |")
    w("|---|---|---|---|---|")
    for key, label in LADDER:
        s = pol[key]["summary"]
        cr = s["cum_reward"]
        cell = f"{f(cr['mean'])} {{{f(cr['ci_users'][0])}, {f(cr['ci_users'][1])}}}"
        if cr["ci_seeds"] is not None:
            cell += f" [{f(cr['ci_seeds'][0])}, {f(cr['ci_seeds'][1])}]"
        w(f"| {label} | {cell} | {f(s['mean_reward']['mean'], 4)} | {f(s['session_length']['mean'], 2)} | {cr['mean'] / p_val:.1%} |")
    w(f"\nPersonalization gap (personalized minus non-personalized oracle): {f(gap['mean'])} {ci(gap['ci'])}.\n")

    w("## 2. Acceptance (ADR-0027)\n")
    t1_dp = dp["acceptance"]["T1_duration_probes_within_tolerance"]
    w(f"T1 is two-sided and session-length controlled. Inside category rotation, the shortest and the longest probe must "
      f"each differ from rotation-random by less than {t1_dp['tolerance']:.0%} of the personalization gap: the whole 95% "
      f"interval of the paired difference must lie inside the margin. The {t1_dp['tolerance']:.0%} tolerance was set "
      "after seeing the audit numbers. T2: the personalized oracle beats the non-personalized one with an interval "
      "above 0. The legacy T1 (shortest-first minus random) is shown as a secondary line and is not part of the verdict.\n")
    w("| Reward | Gap | Margin | rotation_shortest - rotation_random | rotation_longest - rotation_random | T1 | T2 | Verdict | Legacy T1 (secondary) |")
    w("|---|---|---|---|---|---|---|---|---|")
    for r in REWARDS:
        a = rewards[r]["acceptance"]
        t1, t2, leg = (a["T1_duration_probes_within_tolerance"], a["T2_personalized_beats_nonpersonalized"],
                       a["T1_legacy_shortest_not_above_random"])
        s_, l_ = t1["rotation_shortest"], t1["rotation_longest"]
        w(f"| {r} | {f(t1['gap'])} {ci(t2['ci'])} | +/-{f(t1['margin'])} | {f(s_['mean'])} {ci(s_['ci'])} "
          f"({s_['share_of_gap']:+.1%}) | {f(l_['mean'])} {ci(l_['ci'])} ({l_['share_of_gap']:+.1%}) | "
          f"{'pass' if t1['pass'] else 'FAIL'} | {'pass' if t2['pass'] else 'FAIL'} | "
          f"**{'PASS' if a['both_pass'] else 'FAIL'}** | {f(leg['mean'])} {ci(leg['ci'])} {'pass' if leg['pass'] else 'fail'} |")
    w("")

    w("## 3. Does tolerating repetition pay? (ADR-0028)\n")
    w("The category-affinity oracle knows each search user's mean reward per category and shows a random available "
      "single-tag video of the chosen category. Its **full cycle** mode shows every rotation category once before any "
      "repeat; **strict** revisits a category as soon as it leaves the 9-item window; **free** repeats a category as "
      f"often as the setting allows. **Baseline (decision field):** the full-cycle policy, because {dec['baseline_reason']}. "
      "The share of gap uses that profile's own gap.\n")
    w("| Profile | N, n_Q | Full cycle | Strict | Free | Gap [95%] |")
    w("|---|---|---|---|---|---|")
    for p, r in div["profiles"].items():
        s = r["summaries"]
        g = r["gap"]
        w(f"| {p} | {r['env_config']['quit_window']}, {r['env_config']['quit_threshold']} | "
          f"{f(s['oracle_affinity_full_cycle']['summary']['cum_reward']['mean'])} | "
          f"{f(s['oracle_affinity_strict']['summary']['cum_reward']['mean'])} | "
          f"{f(s['oracle_affinity_free']['summary']['cum_reward']['mean'])} | {f(g['mean'])} {ci(g['ci'])} |")
    w("\nBoth readings side by side (free minus the reading; cumulative reward [95%], share of gap [95%]):\n")
    w("| Profile | Free - full cycle (baseline reading) | Free - strict (window reading) |")
    w("|---|---|---|")
    for p, r in div["profiles"].items():
        cells = []
        for key in ("free_minus_full_cycle", "free_minus_strict"):
            d = r[key]
            cells.append(f"{f(d['mean'])} {ci(d['ci'])} ({d['share_of_gap']:.1%} "
                         f"[{d['ci_share_of_gap'][0]:.1%}, {d['ci_share_of_gap'][1]:.1%}])")
        w(f"| {p} | " + " | ".join(cells) + " |")
    w("\nHow free minus full cycle splits (cumulative reward, share of that profile's gap):\n")
    w("| Profile | Revisiting after the window: strict - full cycle | Tolerating repeats: free - strict |")
    w("|---|---|---|")
    for p, r in div["profiles"].items():
        c, d = r["strict_minus_full_cycle"], r["free_minus_strict"]
        w(f"| {p} | {f(c['mean'])} {ci(c['ci'])} ({c['share_of_gap']:.1%}) | {f(d['mean'])} {ci(d['ci'])} ({d['share_of_gap']:.1%}) |")
    w("\n| Reading | Share of gap under looser | Claim 2 under the 10% rule |")
    w("|---|---|---|")
    for name, rd in dec["readings"].items():
        tag = " (baseline)" if name == dec["baseline"] else ""
        w(f"| {rd['description']}{tag} | {rd['share_of_gap']['looser']:.1%} | "
          f"{'stands' if rd['claim2_stands_under_rule'] else 'returns'} |")
    w(f"\n**Recorded outcome:** {dec['text']}")
    w(f"\nThe {dec['threshold']:.0%} rule was set {dec['threshold_set']}; the choice of reading was made "
      f"{dec['reading_chosen']}. What the check measures is headroom: for an oracle that already knows each user's "
      "category affinities, the value of knowing how soon a category can be revisited and how many repeats are tolerated. "
      "Whether a policy learns this from the session-ended signal is still to be measured.\n")
    d1 = div["profiles"][d1_key]["d1_tolerance_mismatch"]
    s1 = div["profiles"][d1_key]["summaries"]
    w(f"### 3.1 Diagnostic D1: a tolerance learned for {d1['built_for']}, used under {d1['run_under']}\n")
    w(f"The free category-affinity oracle built for the {d1['built_for']} setting is run in the {d1['run_under']} "
      f"environment and compared with the same oracle built for {d1['run_under']}. This is evidence for the second half "
      "of claim 2: the repeat tolerance has to be learned, because carrying over the wrong one is costly.\n")
    w("| Oracle, run under tighter | Cum reward / session {95% users} [95% seeds] | Session length | Boredom-quit rate |")
    w("|---|---|---|---|")
    for key, label in (("oracle_affinity_free", "free, built for tighter"),
                       ("oracle_affinity_free_built_for_primary", "free, built for primary"),
                       ("oracle_affinity_full_cycle", "full cycle (baseline)")):
        sm = s1[key]["summary"]
        cr = sm["cum_reward"]
        w(f"| {label} | {f(cr['mean'])} {{{f(cr['ci_users'][0])}, {f(cr['ci_users'][1])}}} "
          f"[{f(cr['ci_seeds'][0])}, {f(cr['ci_seeds'][1])}] | {f(sm['session_length']['mean'], 2)} | "
          f"{f(sm['boredom_quit_rate']['mean'], 3)} |")
    lo, sl, mb = d1["loss"], d1["session_length_loss"], d1["mismatched_minus_full_cycle"]
    gap_t = div["profiles"][d1_key]["gap"]
    w(f"\n**Loss per session** (built for tighter minus built for primary, paired over users): {f(lo['mean'])} "
      f"{ci(lo['ci'])}, which is **{lo['share_of_gap']:.1%}** [{lo['ci_share_of_gap'][0]:.1%}, {lo['ci_share_of_gap'][1]:.1%}] "
      f"of the tighter personalization gap ({f(gap_t['mean'])}). Sessions are {f(sl['mean'], 2)} {ci(sl['ci'], 2)} steps "
      f"shorter. Against the full-cycle baseline, the primary-tuned oracle scores {f(mb['mean'])} {ci(mb['ci'])} "
      f"({mb['share_of_gap']:.1%} of the gap).")
    w("\nThe per-profile ladders are in `runs/audit_v1/diversity_level.md`.\n")

    w("## 4. Results per reward candidate (v1, primary profile)\n")
    w("Rows marked [permanent] appear in every results table (ADR-0029).\n")
    titles = {"raw": "raw watch_ratio", "capped5": "watch_ratio capped at 5",
              "duration_pct": "duration-adjusted: play-time percentile within big-matrix duration bucket (frozen reward)"}
    for r in REWARDS:
        w(f"### {titles[r]}\n")
        w(table_without_header(A / f"rewards_{r}.md") + "\n")

    w("## 5. Duration correlation (ADR-0017)\n")
    w(f"Search users, canonical duration, {corr['n_search_rows']:,} search-user rows. The Phase 0 figure (per video, "
      f"first-row duration vs per-video median watch_ratio) replicates as {f(corr['phase0_replication'], 4)}.\n")
    w("| Reward | per video, mean | per video, median | per interaction | 20 buckets, Spearman | 20 buckets, Pearson |")
    w("|---|---|---|---|---|---|")
    for name, v in corr["by_reward"].items():
        w(f"| {name} | {v['per_video_mean']:+.4f} | {v['per_video_median']:+.4f} | {v['per_interaction']:+.4f} | "
          f"{v['buckets_spearman']:+.4f} | {v['buckets_pearson']:+.4f} |")
    w(f"\nBucket count K = {bucket['chosen']['K_requested']}, chosen on big-matrix data only (ADR-0016).\n")

    w("## 6. Quit profiles (ADR-0019)\n")
    w("| Profile | N, n_Q | Random median length | Random mean length | P(reach 30) |")
    w("|---|---|---|---|---|")
    for name, prof in surv["proposal"].items():
        if name.startswith("alternative"):
            continue
        mc = surv["monte_carlo"][f"N={prof['quit_window']},n_Q={prof['quit_threshold']}"]
        w(f"| {name} | {prof['quit_window']}, {prof['quit_threshold']} | {mc['median']:.0f} | {f(mc['mean'], 2)} | {f(mc['reach_max_turn'], 4)} |")
    w(f"\nMonte Carlo over 100,000 random sequences; the harness's own random runs give a mean of "
      f"{f(surv['harness_primary']['mean'], 3)} under primary.\n")

    w("## 7. Integrity, tests, differential check\n")
    w(f"- Frozen files ({len(_integrity.FROZEN_CODE)} code/config/partition files plus "
      f"{len(_integrity.FROZEN_DATA)} data files): {', '.join(f'`{p}`' for p in _integrity.FROZEN_CODE)}; "
      f"data {', '.join(f'`{p}`' for p in _integrity.FROZEN_DATA)}. Any unlisted module inside `kuairec_eval/` fails verification.")
    w(f"- Tests: {tests} (`docs/v1_test_output.txt`).")
    w(f"- Differential check against EasyRL4Rec KuaiEnv (commit `{diff['reference_commit'][:7]}`): {diff['users']} users, "
      f"{diff['sequences']:,} sequences, {diff['reference_steps']:,} reference steps, **{diff['unexplained']} unexplained** "
      "differences. " + "; ".join(f"{x['our_window_mode']} {x['kind']} {x['cause']}: {x['count']:,}" for x in diff["differences"]) + ".")
    w(f"- Unrecorded-pair mask signal (ADR-0020): per-user Spearman with mean duration_pct "
      f"{checks['mask_per user_duration_pct']:+.3f}.\n")

    w("## 8. Commands behind every number\n")
    w("| Section | Command | Output |")
    w("|---|---|---|")
    for sec, cmd, out in [
        ("1, 2, 4", "`.venv/bin/python scripts/audit_rewards.py`", "`runs/audit_v1/rewards_*`, `acceptance.json`"),
        ("3", "`.venv/bin/python scripts/audit_diversity_level.py`", "`runs/audit_v1/diversity_level.{json,md}`"),
        ("5", "`.venv/bin/python scripts/audit_duration_correlation.py --json runs/audit_v1/duration_correlation.json`", "same"),
        ("5 (K)", "`.venv/bin/python scripts/audit_bucket_choice.py --json runs/audit_v1/bucket_choice.json`", "same"),
        ("6", "`.venv/bin/python scripts/audit_survival.py --json runs/audit_v1/survival.json`", "same"),
        ("7", "`.venv/bin/python scripts/audit_data_checks.py --json runs/audit_v1/data_checks.json`", "same"),
        ("7", "`.venv/bin/python scripts/differential.py`", "`runs/differential_summary.json`"),
        ("7", "`.venv/bin/python -m pytest -v`", "`docs/v1_test_output.txt`"),
        ("this file", "`.venv/bin/python scripts/audit_report.py`", "`docs/AUDIT.md`")]:
        w(f"| {sec} | {cmd} | {out} |")
    w("\n## 9. What changed on approval\n")
    w("- A1: the long-video lean is accepted. The four duration probes (plain and inside rotation) and rotation-random "
      "are permanent rows of every results table, and their code is frozen (ADR-0029).")
    w("- A3: T1 is replaced by the two-sided, session-length-controlled probe test with a 5% tolerance set after seeing "
      "the audit numbers. The old T1 remains as a secondary line (ADR-0027).")
    w("- A2: the quit profiles are N=9 with thresholds 2, 1 and 0 (ADR-0019).")
    w("- Added before the freeze: the category-affinity oracle and the diversity-level check (ADR-0028).")
    w("- After the freeze, C1: the full-cycle policy is the baseline for claim 2, and both readings are kept side by side "
      "(ADR-0028). D1, the cost of carrying the primary tolerance into the tighter setting, is measured in section 3.1.")
    (ROOT / "docs" / "AUDIT.md").write_text("\n".join(L) + "\n")
    print(f"wrote docs/AUDIT.md ({len(L)} lines)")


if __name__ == "__main__":
    main()
