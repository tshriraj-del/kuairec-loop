"""Generate docs/PHASE1.md from the Phase 1 output files. No number is typed by hand.

Usage: .venv/bin/python scripts/phase1_report.py
"""
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "runs" / "phase1"
SCORER_LABELS = {"affinity": "(a) user-category affinity", "item_knn": "(b) item-kNN", "ease": "(c) EASE",
                 "ranker_no_duration": "(d) ranker, no duration", "ranker_duration": "(d) ranker, + duration",
                 "ranker_text": "(d) ranker, + duration + caption text"}


def load(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def f(x, d=3):
    return f"{x:.{d}f}"


def ci(c, d=3):
    return f"[{f(c[0], d)}, {f(c[1], d)}]"


def pct(x):
    return f"{x:.1%}"


def row_line(label, r):
    s = r["summary"]
    cr = s["cum_reward"]
    cell = f"{f(cr['mean'])} {{{f(cr['ci_users'][0])}, {f(cr['ci_users'][1])}}}"
    if cr["ci_seeds"] is not None:
        cell += f" [{f(cr['ci_seeds'][0])}, {f(cr['ci_seeds'][1])}]"
    dp = r["duration_profile"]
    return (f"| {label} | {cell} | {f(s['mean_reward']['mean'], 4)} | {f(s['session_length']['mean'], 2)} | "
            f"{f(s['catalog_coverage']['mean'], 4)} | {f(s['top_category_share']['mean'], 3)} | "
            f"{f(dp['mean_duration_percentile'])} | {f(dp['median_duration_s'], 1)} |")


HEADER = ("| Policy | Cum reward / session {95% users} [95% seeds] | Reward / rec | Session length | Coverage | "
          "Top-category share | Mean duration percentile | Median duration (s) |\n|---|---|---|---|---|---|---|---|")


def main():
    data, tb, tr, emb = load("data_report.json"), load("tuning_base.json"), load("tuning_ranker.json"), load("embed_report.json")
    lad, sc, off, fin, grid = (load("ladder_search.json"), load("scorers_search.json"), load("offline_search.json"),
                               load("final_shadow.json"), load("env_grid.json"))
    ledger = [json.loads(x) for x in (R / "ledger.jsonl").read_text().splitlines() if x.strip()]
    L = []
    w = L.append
    rows, comp = lad["rows"], sc["comparisons"]
    probe = lad["stronger_probe"]
    w("# Phase 1: the base recommender\n")
    w("_Generated by `.venv/bin/python scripts/phase1_report.py` from `runs/phase1/`. Do not edit by hand._\n")
    any_row = next(iter(rows.values()))
    w(f"Frozen evaluator v1, manifest `{any_row['manifest_digest'][:16]}`, primary quit setting, reward duration_pct. "
      "Development on the search partition (847 users); the shadow partition used once for the final table; the "
      "holdout never read. Every scorer serves through the same rule-aware slate (ADR-0035).\n")

    if fin:
        g, best = fin["gate"], fin["gate"]["best_scorer"]
        c = fin["comparisons"]
        w("## 1. Verdict (shadow partition)\n")
        w(f"- Best scorer on search: **{SCORER_LABELS[best]}** ({g['chosen_on']}).")
        w(f"- **Claim 1 {'PASSES' if g['claim1_passes'] else 'FAILS'}.** Against rotation-random: {f(c['vs_rotation_random']['mean'])} "
          f"{ci(c['vs_rotation_random']['ci'])}; against the stronger duration probe ({probe}): "
          f"{f(c['vs_stronger_probe']['mean'])} {ci(c['vs_stronger_probe']['ci'])}.")
        w(f"- Against the non-personalized oracle: {f(c['vs_nonpersonalized_oracle']['mean'])} "
          f"{ci(c['vs_nonpersonalized_oracle']['ci'])}, so it {'beats' if g['beats_nonpersonalized_oracle'] else 'does not beat'} it.")
        gc_ = c["gap_captured"]
        w(f"- **Gap captured:** {pct(gc_['point'])} [{pct(gc_['ci'][0])}, {pct(gc_['ci'][1])}] of the personalization gap "
          f"(scorer minus non-personalized oracle, divided by the gap {f(fin['gap']['mean'])} {ci(fin['gap']['ci'])}).\n")

    w("## 2. Training data (item 1)\n")
    w(f"Big-matrix rows {data['big_rows']:,}; rows with a finite label {data['rows_label_finite']:,} "
      f"(coverage {pct(data['label_coverage_of_usable_rows'])}); rows without a timestamp {data['rows_without_timestamp']:,}; "
      f"rows dropped as unusable {data['rows_dropped_unusable']:,}. Keeping the first view of each (user, video) pair drops "
      f"{data['repeat_view_rows_dropped']:,} repeat-view rows and leaves {data['pairs']:,} pairs (ADR-0030).\n")
    t = data["time"]
    w(f"Windows by first-view time: T_fit {t['first_view_min']} to {t['fit_end']}, T_rank to {t['rank_end']}, "
      f"T_val to {t['first_view_max']}. Validation users: {data['users']['validation_users (>= min_val_pairs catalog pairs in T_val)']:,} "
      f"with {data['users']['validation_targets (their T_val catalog pairs)']:,} targets. Their non-catalog history before T_val has "
      f"median {f(data['history_sizes_non_catalog']['validation_users_before_T_val']['median'], 0)} pairs; the "
      f"{data['users']['catalog_cold (no catalog pair at all)']:,} catalog-cold users the environment serves have median "
      f"{f(data['history_sizes_non_catalog']['catalog_cold_users_all_time']['median'], 0)}.\n")

    w("## 3. Offline tuning on the big-matrix validation split (item 4)\n")
    floor = tb["rows"][0]["ndcg_at_10"]
    w(f"NDCG@10 over each validation user's T_val catalog pairs, gains = label. Constant scores give **{f(floor, 4)}**, "
      "so the lifts below are small: ranking a user's own exposures is a narrow test.\n")
    w("| Scorer | Configuration | NDCG@10 | Lift over constant |\n|---|---|---|---|")
    for r in tb["rows"][1:]:
        sel = tb["selected"][r["scorer"]]["params"] == r["params"]
        w(f"| {r['scorer']}{' (selected)' if sel else ''} | {json.dumps(r['params'])} | {f(r['ndcg_at_10'], 4)} | "
          f"{r['ndcg_at_10'] - floor:+.4f} |")
    if tr:
        w(f"\nRanker: {tr['train_rows']:,} training rows in {tr['train_groups']:,} users (T_rank), {tr['val_rows']:,} validation "
          f"rows in {tr['val_groups']:,} users; features from T_fit fits, video statistics before {tr['video_stats_cutoff_date']}. "
          f"Constant floor on this set {f(tr['constant_floor_ndcg_at_10'], 4)}. Caption text: {emb['videos_with_text']:,} of "
          f"{emb['videos']:,} videos, model `{emb['model']}`.\n")
        w("| Variant | Features | num_leaves | Best iteration | NDCG@10 | Top features by gain share |\n|---|---|---|---|---|---|")
        for v, d in tr["variants"].items():
            best = max(d["trials"], key=lambda x: x["ndcg_at_10"])
            top = ", ".join(f"{n} {s:.0%}" for n, s in d["top_gain_share"][:5])
            w(f"| {v} | {d['n_features']} | {best['num_leaves']} | {best['best_iteration']} | {f(best['ndcg_at_10'], 4)} | {top} |")
        w("")

    w("## 4. Search partition results (item 5)\n")
    w(f"Catalog mean duration percentile is {f(any_row['duration_profile']['catalog_mean_duration_percentile'])} and its median "
      f"duration {f(any_row['duration_profile']['catalog_median_duration_s'], 1)} s; the two duration columns show how far each "
      "policy's recommendations move from the catalog.\n")
    w(HEADER)
    for n in ("random", "rotation_random", "shortest_first", "longest_first", "rotation_shortest", "rotation_longest",
              "oracle_affinity_strict", "oracle_affinity_free", "oracle_nonpersonalized", "oracle_personalized"):
        w(row_line(rows[n]["label"], rows[n]))
    for n, r in sc["rows"].items():
        w(row_line(f"**{SCORER_LABELS[n]}**", r))
    w(f"\nStronger duration probe on search: `{probe}`. Personalization gap: {f(comp['gap']['mean'])} {ci(comp['gap']['ci'])}.\n")

    w("## 5. Comparisons on search (item 6)\n")
    w("Paired bootstraps over the 847 search users, cumulative reward per session, 10,000 resamples.\n")
    w("| Scorer | - rotation-random | - stronger probe | - non-personalized oracle | Gap captured [95%] | - scorer (a) |\n|---|---|---|---|---|---|")
    for n, d in comp["per_scorer"].items():
        a = d.get("vs_scorer_a")
        w(f"| {SCORER_LABELS[n]} | {f(d['vs_rotation_random']['mean'])} {ci(d['vs_rotation_random']['ci'])} | "
          f"{f(d['vs_stronger_probe']['mean'])} {ci(d['vs_stronger_probe']['ci'])} | "
          f"{f(d['vs_nonpersonalized_oracle']['mean'])} {ci(d['vs_nonpersonalized_oracle']['ci'])} | "
          f"{pct(d['gap_captured']['point'])} [{pct(d['gap_captured']['ci'][0])}, {pct(d['gap_captured']['ci'][1])}] | "
          f"{(f(a['mean']) + ' ' + ci(a['ci'])) if a else 'n/a'} |")
    con = load("contrasts_search.json")
    if con:
        w("\nWhat each ranker step contributes (paired, cumulative reward per session and reward per recommendation; "
          "`.venv/bin/python scripts/phase1_env.py contrasts`, no further environment run):\n")
        w("| Contrast | Cum reward [95%] | Reward / rec [95%] |\n|---|---|---|")
        for k, v in con.items():
            mr = v["mean_reward"]
            w(f"| {k} | {f(v['mean'])} {ci(v['ci'])} | {f(mr['mean'], 4)} {ci(mr['ci'], 4)} |")
    da = comp["per_scorer"]["affinity"]
    sh = lambda r: f"{pct(r['point'])} [{pct(r['ci'][0])}, {pct(r['ci'][1])}]"  # noqa: E731
    w(f"\nScorer (a) as a share of the category-affinity oracle's lift over rotation-random: "
      f"{sh(da['share_of_affinity_strict_lift'])} of the window-rotation oracle's lift, "
      f"{sh(da['share_of_affinity_free_lift'])} of the free oracle's lift.\n")

    w("## 6. Offline ranking check on search (item 7)\n")
    w(f"Each user's action set ranked against their recorded rewards. NDCG@10 uses the reward as the graded gain; "
      f"Recall@10 counts a video as relevant when its reward is at least {off['relevance_threshold']} "
      f"(on average {f(off['mean_relevant_per_user'], 0)} relevant videos per user) and divides the hits in the top 10 by "
      "min(10, relevant). Common values are the non-personalized oracle's in-sample means.\n")
    w("| Scorer | NDCG@10 | Recall@10 |\n|---|---|---|")
    for n, r in off["rows"].items():
        w(f"| {SCORER_LABELS.get(n, n)} | {f(r['ndcg_at_10'], 4)} | {f(r['recall_at_10'], 4)} |")
    w("")

    if fin:
        w("## 7. Final table on shadow (item 8)\n")
        w(HEADER)
        for n in ("random", "rotation_random", "shortest_first", "longest_first", "rotation_shortest", "rotation_longest",
                  "oracle_affinity_strict", "oracle_affinity_free", "oracle_nonpersonalized", "oracle_personalized"):
            w(row_line(fin["ladder"][n]["label"], fin["ladder"][n]))
        w(row_line(f"**{SCORER_LABELS[fin['gate']['best_scorer']]}**", fin["best"]))
        w("")

    w("## 8. Run ledger\n")
    cnt = Counter((e["partition"], e["role"]) for e in ledger)
    w(f"`runs/phase1/ledger.jsonl`: {len(ledger)} seed-level entries ("
      + ", ".join(f"{p} {r}: {n}" for (p, r), n in sorted(cnt.items())) + f"). Grid declared at {grid['declared_at']}; "
      f"first ledger entry at {ledger[0]['at']}. Every entry carries the policy, config hash, seed, partition and the "
      "grid and manifest hashes (ADR-0036).\n")
    w("## 9. Commands\n")
    for cmd in ("scripts/phase1_data.py", "scripts/phase1_embed.py", "scripts/phase1_tune.py", "scripts/phase1_rank.py",
                "scripts/phase1_fit.py", "scripts/phase1_declare.py", "scripts/phase1_env.py ladder --partition search",
                "scripts/phase1_env.py scorers", "scripts/phase1_env.py contrasts", "scripts/phase1_offline.py",
                "scripts/phase1_env.py shadow",
                "scripts/phase1_external.py", "scripts/phase1_report.py"):
        w(f"- `.venv/bin/python {cmd}`")
    (ROOT / "docs" / "PHASE1.md").write_text("\n".join(L) + "\n")
    print(f"wrote docs/PHASE1.md ({len(L)} lines)")


if __name__ == "__main__":
    main()
